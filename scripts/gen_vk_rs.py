"""Generate solana/program/src/vk.rs from SP1's Groth16 Solidity verifier sources.

Usage: python -I gen_vk_rs.py <dir with Groth16Verifier.sol + SP1VerifierGroth16.sol> <proof fixture.json> <out.rs>
All values are emitted as 32-byte big-endian arrays (EIP-197 / alt_bn128 encoding).
"""
import json, re, sys

src_dir, fixture, out = sys.argv[1:4]
g16 = open(f"{src_dir}/Groth16Verifier.sol", encoding="utf-8").read()
sp1 = open(f"{src_dir}/SP1VerifierGroth16.sol", encoding="utf-8").read()

consts = dict(re.findall(r"uint256 constant ([A-Z0-9_]+) = (0x[0-9a-fA-F]+|\d+);", g16))
def be32(v):
    n = int(v, 16) if v.startswith("0x") else int(v)
    return n.to_bytes(32, "big")

need = ["ALPHA_X", "ALPHA_Y",
        "BETA_NEG_X_0", "BETA_NEG_X_1", "BETA_NEG_Y_0", "BETA_NEG_Y_1",
        "GAMMA_NEG_X_0", "GAMMA_NEG_X_1", "GAMMA_NEG_Y_0", "GAMMA_NEG_Y_1",
        "DELTA_NEG_X_0", "DELTA_NEG_X_1", "DELTA_NEG_Y_0", "DELTA_NEG_Y_1",
        "CONSTANT_X", "CONSTANT_Y", "R"]
pubs = sorted({int(m) for m in re.findall(r"PUB_(\d+)_X", g16)})
need += [f"PUB_{i}_{c}" for i in pubs for c in "XY"]
missing = [k for k in need if k not in consts]
assert not missing, missing

version = re.search(r'return "(v[0-9.]+)";', sp1).group(1)
verifier_hash = re.search(r"VERIFIER_HASH\(\).*?return (0x[0-9a-f]{64});", sp1, re.S).group(1)
vk_root = re.search(r"VK_ROOT\(\).*?return (0x[0-9a-f]{64});", sp1, re.S).group(1)
program_vkey = json.load(open(fixture))["vkey"]

def arr(b):
    return "[" + ", ".join(f"0x{x:02x}" for x in b) + "]"

lines = [
    "// @generated by scripts/gen_vk_rs.py — do not edit.",
    f"// Source: SP1 {version} Groth16 circuit artifacts (~/.sp1/circuits/groth16/{version}/",
    "// Groth16Verifier.sol + SP1VerifierGroth16.sol, MIT, Succinct Labs). Big-endian field elements.",
    "",
    f'pub const SP1_CIRCUIT_VERSION: &str = "{version}";',
    f"pub const NUM_PUBLIC_INPUTS: usize = {len(pubs)};",
    f"pub const VERIFIER_HASH: [u8; 32] = {arr(be32(verifier_hash))};",
    f"pub const VK_ROOT: [u8; 32] = {arr(be32(vk_root))};",
    "/// vkey hash of the bridge SP1 guest (program/: segment + deposit kinds), from the proof fixture.",
    f"pub const PROGRAM_VKEY: [u8; 32] = {arr(be32(program_vkey))};",
]
for k in need:
    lines.append(f"pub const {k}: [u8; 32] = {arr(be32(consts[k]))};")
lines.append("pub const PUB: [([u8; 32], [u8; 32]); NUM_PUBLIC_INPUTS] = [" +
             ", ".join(f"(PUB_{i}_X, PUB_{i}_Y)" for i in pubs) + "];")
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(f"{version}: {len(pubs)} public inputs, verifier_hash={verifier_hash[:10]}…, program_vkey={program_vkey[:10]}… -> {out}")
